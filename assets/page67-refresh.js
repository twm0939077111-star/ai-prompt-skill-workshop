  const PROMPT_SLIDE = '[data-vm-slide-id="theme01_page030-7"]';
  const RESULT_SLIDE = '[data-vm-slide-id="theme01_page076-8"]';

  function el(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (typeof text === "string") node.textContent = text;
    return node;
  }

  function buildHeader(kicker, titleHtml, noteHtml) {
    const head = el("header", "p67-head");
    const left = el("div");
    left.appendChild(el("div", "p67-kicker", kicker));
    const title = el("h2");
    title.innerHTML = titleHtml;
    left.appendChild(title);
    const note = el("div", "p67-head-note");
    note.innerHTML = noteHtml;
    head.append(left, note);
    return head;
  }

  function buildPromptPage() {
    const page = el("div", "p67-page p67-prompt-page");
    page.appendChild(buildHeader(
      "GOOD PROMPT｜四篇完整版",
      "四篇完整 Prompt，先把<strong>想要的畫面</strong>說清楚",
      "點選卡片 · <b>閱讀／複製完整版</b>"
    ));

    const grid = el("main", "p67-prompt-grid");
    CASES.forEach((item, index) => {
      const card = el("article", "p67-prompt-card");
      card.style.setProperty("--accent", item.accent);
      card.tabIndex = 0;
      card.setAttribute("role", "button");
      card.setAttribute("aria-label", `開啟 ${item.title} 完整 Prompt`);
      card.dataset.promptIndex = String(index);

      const top = el("div", "p67-card-top");
      top.appendChild(el("span", "p67-number", item.no));
      const title = el("div", "p67-card-title");
      title.append(el("b", "", item.title), el("span", "", item.en));
      top.append(title, el("span", "p67-card-type", item.type));

      card.append(top, el("p", "p67-card-lead", item.lead));
      const summary = el("p", "p67-card-summary");
      summary.innerHTML = item.summary;
      card.appendChild(summary);

      const bottom = el("div", "p67-card-bottom");
      const chipRow = el("div", "p67-chip-row");
      item.chips.forEach((chip) => chipRow.appendChild(el("span", "", chip)));
      const open = el("button", "p67-open");
      open.type = "button";
      open.dataset.promptIndex = String(index);
      open.innerHTML = "看完整指令 <span>↗</span>";
      bottom.append(chipRow, open);
      card.appendChild(bottom);

      grid.appendChild(card);
    });
    page.appendChild(grid);
    return page;
  }

